% -------------------------------------------------------------------------
% Helper: Call Google Gemini REST API
% -------------------------------------------------------------------------
function apiResp = call_gemini_api(userQuery, ehr, pred, etdrs, activeLang, config)
    apiResp = '';
    apiKey = '';
    if isfield(config, 'gemini_api_key') && ~isempty(config.gemini_api_key)
        apiKey = strtrim(config.gemini_api_key);
    end
    if isempty(apiKey)
        apiKey = getenv('GEMINI_API_KEY');
    end
    if isempty(apiKey), return; end

    model = 'gemini-2.5-flash';
    if isfield(config, 'model') && ~isempty(config.model)
        model = config.model;
    end

    % Build concise patient context prompt
    ctx = sprintf(['Patient Context:\n' ...
        '- Name: %s, Age: %d, Sex: %s, ID: %s\n' ...
        '- Diabetes Duration: %d yrs (%s), Last HbA1c: %.1f%% (Date: %s)\n' ...
        '- Blood Pressure: %s, Hypertension: %s, Nephropathy: %s\n' ...
        '- Active Medications: %s\n'], ...
        ehr.name, ehr.age, ehr.sex, ehr.id, ...
        ehr.diabetesDurationYears, ehr.diabetesType, ehr.lastHbA1c, ehr.hba1cDate, ...
        ehr.bloodPressure, ehr.hypertension, ehr.nephropathy, ...
        strjoin(ehr.medications, ', '));

    if ~isempty(pred)
        ctx = [ctx, sprintf(['- Today''s Retinal Scan: Grade %d (%s), Confidence: %.1f%%, Referable Risk: %.1f%%, Urgency: %s, Is Referable: %s\n'], ...
            pred.grade, pred.gradeName, pred.confidence*100, pred.referableScore*100, ...
            pred.referralUrgency, ternary(pred.isReferable, 'YES', 'NO'))];
    end
    if ~isempty(etdrs) && isfield(etdrs, 'etdrsStage')
        ctx = [ctx, sprintf('- ETDRS Staging: %s\n', etdrs.etdrsStage)];
    end

    langNote = 'Answer in English.';
    if strcmp(activeLang, 'hi') || contains(lower(userQuery), {'hindi', 'हिन्दी'})
        langNote = 'Answer in natural, professional Hindi (Devanagari script).';
    elseif strcmp(activeLang, 'mr')
        langNote = 'Answer in Marathi.';
    elseif strcmp(activeLang, 'kn')
        langNote = 'Answer in Kannada.';
    end

    sysPrompt = sprintf(['You are RetinaCare AI, an expert clinical tele-ophthalmology assistant at an Indian rural Primary Health Centre (PHC).\n' ...
        'Answer the user''s question directly, accurately, and concisely based strictly on the patient data provided.\n' ...
        'STRICT CLINICAL RULES:\n' ...
        '1. Answer ONLY what the user asked. Do NOT dump the patient''s entire record or medication list unless asked.\n' ...
        '2. Keep answers focused, clear, and direct (2-4 bullet points or short paragraphs).\n' ...
        '3. If asked about disease or condition, state clearly that the disease is Diabetic Retinopathy and explain its stage.\n' ...
        '4. %s\n\n' ...
        '%s\n\n' ...
        'Clinician Question: %s'], langNote, ctx, userQuery);

    url = sprintf('https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s', model, apiKey);

    payload = struct('contents', struct('parts', struct('text', sysPrompt)));

    try
        options = weboptions('MediaType', 'application/json', 'Timeout', 10, 'RequestMethod', 'post');
        rawResp = webwrite(url, payload, options);
        if isfield(rawResp, 'candidates') && ~isempty(rawResp.candidates)
            c = rawResp.candidates(1);
            if isfield(c, 'content') && isfield(c.content, 'parts') && ~isempty(c.content.parts)
                apiResp = char(c.content.parts(1).text);
            end
        end
    catch ME
        apiResp = '';
    end
end

