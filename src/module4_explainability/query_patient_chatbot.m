            else
                expStr = 'Moderate NPDR. Presence of microaneurysms, blot hemorrhages, or hard exudates, requiring retinal consultation.';
            end
        case 3
            if strcmp(lang, 'hi')
                expStr = 'गंभीर डायबिटिक रेटिनोपैथी (Severe NPDR)। रेटिना के बड़े हिस्से में खून की नलियां बंद हो चुकी हैं। तुरंत उपचार न मिलने पर दृष्टि जा सकती है।';
            else
